"""Private storage for proof media (C2 "Proof media storage").

The API is the only way in or out: nothing here is ever served by a web server
directly, and readers go through GET /media/{id}, which checks who is asking
(BE-42). Keys are generated by the API, never taken from the client.
"""
from __future__ import annotations

import logging
import os
import threading
from pathlib import Path
from typing import Protocol

logger = logging.getLogger(__name__)


class ObjectNotFoundError(Exception):
    pass


class ObjectStore(Protocol):
    def put(self, key: str, data: bytes) -> None:
        ...

    def get(self, key: str) -> bytes:
        ...

    def delete(self, key: str) -> None:
        """Removes the object; deleting something already gone is not an error."""
        ...


class LocalObjectStore:
    """Files on the API host's disk, readable only by the API's own user.

    Good enough for development and a single API instance. Swap in an S3-style
    store behind the same three methods when the API runs on more than one host.
    """

    def __init__(self, root: Path):
        self.root = root
        self.root.mkdir(mode=0o700, parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if self.root.resolve() not in path.parents:
            raise ValueError("Object key escapes the storage root")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, "wb") as file:
            file.write(data)

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as error:
            raise ObjectNotFoundError(key) from error

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink()
        except FileNotFoundError:
            logger.info("Object already deleted", extra={"key": key})


class InMemoryObjectStore:
    """The fake object store the test seam uses."""

    def __init__(self):
        self._objects: dict[str, bytes] = {}
        self._lock = threading.Lock()

    def put(self, key: str, data: bytes) -> None:
        with self._lock:
            self._objects[key] = data

    def get(self, key: str) -> bytes:
        with self._lock:
            try:
                return self._objects[key]
            except KeyError as error:
                raise ObjectNotFoundError(key) from error

    def delete(self, key: str) -> None:
        with self._lock:
            self._objects.pop(key, None)

    def __contains__(self, key: str) -> bool:
        with self._lock:
            return key in self._objects
