#!/usr/bin/env bash
# Build the production frontend for ChatGPT Sites against the demo HTTPS API.
# Does not publish to Sites. Does not start the Vite DEV server.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=demo-common.sh
source "$SCRIPT_DIR/demo-common.sh"

demo_mkdir
demo_load_env

API_URL="${1:-}"
if [[ -z "$API_URL" && -f "$URL_FILE" ]]; then
  API_URL="$(tr -d '[:space:]' <"$URL_FILE")"
fi
if [[ -z "$API_URL" ]]; then
  echo "ERROR: no API URL. Pass it as argv1 or run scripts/start-demo.sh first." >&2
  echo "Usage: bash scripts/build-sites-frontend.sh https://your-tunnel.example" >&2
  exit 1
fi
API_URL="${API_URL%/}"

if [[ "$API_URL" != https://* ]]; then
  echo "ERROR: Sites builds must use an HTTPS API origin (got: $API_URL)" >&2
  exit 1
fi

DISCUSSIONS_API="${VITE_DISCUSSIONS_API:-false}"
if [[ "$DISCUSSIONS_API" == "true" ]]; then
  echo "WARNING: building with VITE_DISCUSSIONS_API=true."
  echo "         Only do this after Grove/quest ACL verification on this backend."
fi

CLASSROOM_DEMO="${VITE_CLASSROOM_DEMO:-true}"
if [[ "$CLASSROOM_DEMO" == "true" ]]; then
  echo "Building with VITE_CLASSROOM_DEMO=true (admin/mod login aliases on the form)."
  echo "         Backend must run with QUESTBOARD_CLASSROOM_DEMO=1 against presentation DB."
fi

OUT_ENV="$ROOT/apps/frontend/.env.sites.local"
cat >"$OUT_ENV" <<EOF
# Generated by scripts/build-sites-frontend.sh — gitignored. Do not commit.
VITE_API_BASE_URL=$API_URL
VITE_ROLE_REQUESTS_ENABLED=true
VITE_QUESTS_ENABLED=true
VITE_CATALOGUE_ENABLED=true
VITE_QUESTS_DEMO=false
VITE_PROOFS_DEMO=false
VITE_PROOFS_API=true
VITE_MODERATION_API=true
VITE_REWARDS_DEMO=false
VITE_REWARDS_API=true
VITE_DISCUSSIONS_DEMO=false
VITE_DISCUSSIONS_API=$DISCUSSIONS_API
VITE_CLASSROOM_DEMO=$CLASSROOM_DEMO
EOF

echo "Wrote $OUT_ENV"
echo "Building production frontend with live adapters (demo adapters off)…"
(
  cd "$ROOT/apps/frontend"
  # Vite loads .env, .env.local, .env.production — use explicit env for this build.
  set -a
  # shellcheck disable=SC1090
  source "$OUT_ENV"
  set +a
  npm run build
)

echo
echo "Build OK → $ROOT/apps/frontend/dist/"
echo "Upload that folder to ChatGPT Sites (or your static host)."
echo "QR code → ChatGPT Sites frontend URL (stable if the Sites URL is unchanged)."
echo "When only the API tunnel changes: rebuild + re-publish dist with the new VITE_API_BASE_URL;"
echo "keep the same QR if it already targets the unchanged Sites URL."
echo "Tunnel URL is only VITE_API_BASE_URL=$API_URL (never put the tunnel URL on the QR)."
if [[ -n "${SITES_ORIGIN:-}" ]]; then
  echo "Configured SITES_ORIGIN=$SITES_ORIGIN"
fi
